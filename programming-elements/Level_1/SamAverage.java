public class SamAverage {
    public static void main(String[] args) {
        int maths = 94;
        int physics = 95;
        int chemistry = 96;

        // Calculate average
        double average = (maths + physics + chemistry) / 3.0;

        // Output the result
        System.out.printf("Sam's average mark in PCM is %.2f%n", average);
    }
}